export const getProductById = (id) => {
  return products.find(
    (product) => product.id === Number(id)
  );
};


export const getProductsByCategory = (category) => {
  if (!category) {
    return products;
  }

  return products.filter(
    (product) =>
      product.category.toLowerCase() ===
      category.toLowerCase()
  );
};